namespace App\Data;

// ════════════════════════════════════════════════════════════
//  قطاعات وزارة الداخلية المعتمدة — المصدر الوحيد للقائمة.
//
//  مصدرها ملف الوزارة «اكواد القطاعات»: لكل قطاع اسمٌ مختصر يُعرض في
//  الشاشات والقوائم، واسمٌ رسمي كامل يُكتب في المخاطبات والتقارير، ورمزٌ
//  لاتيني ثنائي هو بادئة رمز المشارك (CD-001…).
//
//  تقرؤها الهجرة والبذر معاً: لو نُسخت القائمة في الاثنين لتفرّعت النسختان
//  عند أول تعديل، فبقيت قاعدةٌ مُهاجَرة تخالف قاعدةً مبذورة بلا إنذار.
//
//  ⚠ is_military = false للجميع بقرارٍ صريح: التصنيف عسكري/مدني يحكم
//    «الرتبة» أم «المرتبة» في الاستيراد وتصنيفَ الطبقة، فلا يُخمَّن هنا.
//    يضبطه صاحب المنصّة لكل قطاع من شاشة الإعدادات، وضبطُه لا يُدهس:
//    البذر والهجرة يكتبان التصنيف عند الإنشاء الأول فقط.
// ════════════════════════════════════════════════════════════
final class MoiSectors
{
    // [الرمز، الاسم المختصر، الاسم الرسمي الكامل]
    private const ROWS = [
        ['CD', 'الدفاع المدني',   'المديرية العامة للدفاع المدني'],
        ['PS', 'الأمن العام',      'المديرية العامة للأمن العام'],
        ['PP', 'الجوازات',         'المديرية العامة للجوازات'],
        ['PR', 'السجون',           'المديرية العامة للسجون'],
        ['CV', 'الأحوال المدنية',  'وكالة وزارة الداخلية للأحوال المدنية'],
        ['BG', 'حرس الحدود',       'المديرية العامة لحرس الحدود'],
        ['PM', 'أمن المنشآت',      'قوات أمن المنشآت'],
        ['SC', 'الكلية الأمنية',   'كلية الملك فهد الأمنية'],
        ['NC', 'مكافحة المخدرات',  'المديرية العامة لمكافحة المخدرات'],
        ['DW', 'ديوان الوزارة',    'ديوان وزارة الداخلية'],
        ['MS', 'الخدمات الطبية',   'الإدارة العامة للخدمات الطبية'],
        ['RG', 'إمارات المناطق',   'وكالة الوزارة لشؤون المناطق'],
        ['MJ', 'المجاهدين',        'الإدارة العامة للمجاهدين'],
        ['OC', '911',              'المركز الوطني للعمليات الأمنية'],
        ['CL', 'النادي',           'نادي منسوبي وزارة الداخلية'],
        ['IS', 'الأمن الصناعي',    'الهيئة العليا للأمن الصناعي'],
        ['SP', 'الأمن والحماية',   'القوات الخاصة للأمن والحماية'],
        ['SR', 'الأفواج الأمنية',  'وكالة وزارة الداخلية الأفواج الأمنية'],
        ['SE', 'الأمن البيئي',     'القوات الخاصة للأمن البيئي'],
    ];

    // صفوف جاهزة للإدراج: البادئة = الرمز نفسه (رمز المشارك CD-001)
    public static function rows(): array
    {
        return array_map(fn ($r) => [
            'code' => $r[0],
            'name_ar' => $r[1],
            'full_name_ar' => $r[2],
            'participant_prefix' => $r[0],
            'is_military' => false,
        ], self::ROWS);
    }

    public static function codes(): array
    {
        return array_column(self::ROWS, 0);
    }

    // إدخال القائمة في القاعدة — يُستدعى من البذر، وقابل لإعادة التشغيل.
    //
    // القطاع القائم لا يُدهس: اسمُه المعروض وتصنيفُه العسكري وبادئتُه تُحرَّر من
    // شاشة الإعدادات، فبذرٌ يعيدها إلى الافتراضي يمحو ضبطاً اختاره صاحب المنصّة
    // — وأخطرُه التصنيف، إذ يقلب «الرتبة» إلى «المرتبة» في الاستيراد بلا إنذار.
    // الاسم الرسمي وحده يُزامَن: مرجعيٌّ من ملف الوزارة لا يُحرَّر من الشاشة.
    public static function sync(): void
    {
        foreach (self::rows() as $row) {
            $sector = \App\Models\Sector::where('code', $row['code'])->first();
            $sector
                ? $sector->update(['full_name_ar' => $row['full_name_ar']])
                : \App\Models\Sector::create($row);
        }
    }

    // القطاعات الثمانية التجريبية التي سبقت القائمة المعتمدة، ومقابلُها فيها.
    // تُقرأ من الهجرة (حذف غير المرتبط) ومن أمر التقاعد (نقل المرتبط ثم الحذف).
    public const LEGACY_MAP = [
        'DA' => 'CD',   // الدفاع        → الدفاع المدني
        'HI' => 'MS',   // الصحة         → الخدمات الطبية
        'MA' => 'PP',   // المالية        → الجوازات
        'TR' => 'RG',   // النقل          → إمارات المناطق
        'EN' => 'BG',   // الطاقة         → حرس الحدود
        'ED' => 'DW',   // التعليم        → ديوان الوزارة
        'HO' => 'PR',   // الإسكان        → السجون
        'CO' => 'OC',   // الاتصالات      → المركز الوطني للعمليات الأمنية
    ];
}
