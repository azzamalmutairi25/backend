<?php

// ════════════════════════════════════════════════════════════
//  إعدادات أمنية تُقرأ من البيئة — ولا بدّ أن تكون في ملف إعدادات.
//
//  لماذا هنا لا عبر env() مباشرةً في الشيفرة؟ لأن الإنتاج يشغّل
//  `php artisan config:cache`، وعندها يتخطّى الإطارُ تحميلَ ملف .env
//  كلياً، فيرجع env() القيمةَ الافتراضية في كل نداء خارج ملفات الإعدادات.
//
//  أثر ذلك كان صامتاً وخطيراً: TRUSTED_PROXIES يصير فارغاً خلف الوسيط
//  العكسي، فيُفهرَس تقييد المعدّل على عنوان الوسيط — كل مستخدمي المنصّة
//  (وكل المشاركين على البوّابة العامة) في دلوٍ واحد، وتُسجَّل عناوين الوسيط
//  في سجل التدقيق بدل عناوين أصحابها.
//
//  env() داخل ملف إعدادات آمن: يُقيَّم لحظة بناء الذاكرة المؤقّتة فيُخبَز فيها.
// ════════════════════════════════════════════════════════════

return [

    // عناوين الوسطاء العكسيين الموثوقين (CIDR أو IP، مفصولة بفواصل).
    // فارغ = لا نثق بأحد؛ لا تستعمل '*' فهي تسمح بانتحال X-Forwarded-For.
    'trusted_proxies' => array_values(array_filter(array_map(
        'trim',
        explode(',', (string) env('TRUSTED_PROXIES', ''))
    ))),

    // سقف الطلبات لكل مستخدم مُصادَق في الدقيقة على كل مسارات /api
    'api_rate_limit' => (int) env('API_RATE_LIMIT', 300),

];
